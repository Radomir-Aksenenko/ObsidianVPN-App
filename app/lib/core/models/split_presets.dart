// Готовые наборы для раздельного туннелирования.
// Записи того же формата, что и пользовательский ввод: домены, IPv4/IPv6 адреса и CIDR.
// Каждый набор проходит тот же разбор, что и ввод пользователя (SplitRuleParser).
//
// Источники и даты снимков (портировано из удалённого iOS-клиента):
// - Telegram: https://core.telegram.org/resources/cidr.txt, снимок 2026-10-08 (14 подсетей, см. ниже).
// - Google (YouTube, Google Video): https://www.gstatic.com/ipranges/goog.json, снимок 2026-10-08
//   (creationTime файла 2026-10-08T01:06:45). Все адреса Google, а не только YouTube:
//   в режиме «Только список» через VPN пойдет весь трафик Google, в «Кроме списка» он пойдет напрямую.
//   Кэши Google Global Cache внутри провайдеров в этот файл не входят.
// - Российские сервисы и локальная сеть: списки доменов и диапазоны RFC 1918, RFC 3927, RFC 4193, RFC 4291.
// Списки обновлять вручную, сверяя с источниками перед релизом.

/// Готовые наборы правил. Имена (`name`) совпадают с wire-значениями split_presets.
enum SplitPreset {
  telegram(titleRu: 'Telegram', titleEn: 'Telegram'),
  youtube(titleRu: 'YouTube и Google Video', titleEn: 'YouTube and Google Video'),
  ru(titleRu: 'Российские сервисы', titleEn: 'Russian services'),
  local(titleRu: 'Локальная сеть', titleEn: 'Local network');

  const SplitPreset({required this.titleRu, required this.titleEn});

  final String titleRu;
  final String titleEn;

  /// Записи набора в формате пользовательского ввода.
  List<String> get entries {
    switch (this) {
      case SplitPreset.telegram:
        return _telegram;
      case SplitPreset.youtube:
        return _youtube;
      case SplitPreset.ru:
        return _russianServices;
      case SplitPreset.local:
        return _localNetwork;
    }
  }

  /// Значение для JSON (split_presets).
  String get wire => name;

  /// Набор по значению из JSON. Неизвестные значения возвращают null.
  static SplitPreset? fromWire(String? raw) {
    if (raw == null) return null;
    for (final preset in SplitPreset.values) {
      if (preset.wire == raw) return preset;
    }
    return null;
  }
}

